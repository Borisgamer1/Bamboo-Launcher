export type LanguageType = "en" | "de";

export function formatMessage(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function localeFor(lang: LanguageType): string {
  return lang === "de" ? "de-DE" : "en-US";
}

export function formatNumber(value: number, lang: LanguageType): string {
  return value.toLocaleString(localeFor(lang));
}

const COMPACT_UNITS: Record<LanguageType, Array<{ value: number; suffix: string }>> = {
  de: [
    { value: 1_000_000_000_000, suffix: "Bio." },
    { value: 1_000_000_000, suffix: "Mrd." },
    { value: 1_000_000, suffix: "Mio." },
    { value: 1_000, suffix: "Tsd." },
  ],
  en: [
    { value: 1_000_000_000_000, suffix: "T" },
    { value: 1_000_000_000, suffix: "B" },
    { value: 1_000_000, suffix: "M" },
    { value: 1_000, suffix: "K" },
  ],
};

/**
 * Compact count for download/follower figures: 16,7 Mio. / 16.7M.
 * Always keeps one decimal place and never abbreviates below one thousand.
 */
export function formatCompactNumber(value: number, lang: LanguageType): string {
  const numeric = Number(value);
  if (!Number.isFinite(numeric)) return formatNumber(0, lang);
  if (Math.abs(numeric) < 1000) return formatNumber(numeric, lang);

  const units = COMPACT_UNITS[lang];
  let index = units.findIndex((unit) => Math.abs(numeric) >= unit.value);
  if (index < 0) return formatNumber(numeric, lang);
  let scaled = numeric / units[index].value;
  // 999,96 Mio. must become 1,0 Mrd., not 1000,0 Mio.
  if (Math.abs(scaled) >= 999.95 && index > 0) {
    index -= 1;
    scaled = numeric / units[index].value;
  }
  const formatted = scaled.toLocaleString(localeFor(lang), {
    minimumFractionDigits: 1,
    maximumFractionDigits: 1,
  });
  // German units are abbreviations with a space (16,7 Mio.), English ones
  // attach directly (16.7M).
  return `${formatted}${lang === "de" ? " " : ""}${units[index].suffix}`;
}

